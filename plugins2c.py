"""Embed the plugins listed in plugins/bundled.txt in the firmware.

Writes include/bundled_plugins.h. On the first boot after flashing, the
firmware copies these plugins to the device's storage so there is something
to run straight away. Runs before every build, like htmlconvert.py.
"""

import glob
import os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO)
    PROJECT_DIR = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))


def c_string(data):
    """Return `data` as C string literals, one source line per literal."""
    lines = []
    for line in data.split(b"\n"):
        escaped = []
        for byte in line + b"\n":
            char = chr(byte)
            if char == "\\":
                escaped.append("\\\\")
            elif char == '"':
                escaped.append('\\"')
            elif char == "\n":
                escaped.append("\\n")
            elif char == "\t":
                escaped.append("\\t")
            elif 32 <= byte < 127:
                escaped.append(char)
            else:
                # Octal, so a following digit cannot be read as part of the escape.
                escaped.append("\\%03o" % byte)
        lines.append('    "%s"' % "".join(escaped))
    return "\n".join(lines)


def generate():
    sources = sorted(glob.glob(os.path.join(PROJECT_DIR, "plugins", "*.lua")))
    # plugins/bundled.txt says which of them go into the firmware. The rest is
    # for the plugin directory only.
    listing = os.path.join(PROJECT_DIR, "plugins", "bundled.txt")
    if os.path.exists(listing):
        with open(listing, "r") as handle:
            wanted = {line.strip() for line in handle if line.strip() and not line.startswith("#")}
        missing = wanted - {os.path.splitext(os.path.basename(path))[0] for path in sources}
        if missing:
            raise SystemExit("plugins2c: plugins/bundled.txt names plugins that do not exist: " + ", ".join(sorted(missing)))
        sources = [path for path in sources if os.path.splitext(os.path.basename(path))[0] in wanted]
    out = [
        "// Generated by plugins2c.py from the plugins listed in plugins/bundled.txt. Do not edit.",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "",
        "struct BundledPlugin {",
        "    const char* name;",
        "    const char* source;",
        "    size_t length;",
        "};",
        "",
    ]
    entries = []
    for index, path in enumerate(sources):
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path, "rb") as handle:
            data = handle.read()
        if data.endswith(b"\n"):
            data = data[:-1]  # c_string adds the final newline back
        out.append("static const char BUNDLED_PLUGIN_%d[] =\n%s;\n" % (index, c_string(data)))
        entries.append('    {"%s", BUNDLED_PLUGIN_%d, sizeof(BUNDLED_PLUGIN_%d) - 1},' % (name, index, index))
    if entries:
        out.append("static const BundledPlugin BUNDLED_PLUGINS[] = {")
        out.extend(entries)
        out.append("};")
    else:
        # An array without elements is not valid C++.
        out.append("static const BundledPlugin* const BUNDLED_PLUGINS = nullptr;")
    out.append("")
    out.append("static const size_t BUNDLED_PLUGIN_COUNT = %d;" % len(sources))
    out.append("")

    target = os.path.join(PROJECT_DIR, "include", "bundled_plugins.h")
    content = "\n".join(out)
    # Leave the file alone when nothing changed, so the build stays incremental.
    if os.path.exists(target):
        with open(target, "r") as handle:
            if handle.read() == content:
                return
    with open(target, "w") as handle:
        handle.write(content)
    print("plugins2c: embedded %d plugins" % len(sources))


generate()
