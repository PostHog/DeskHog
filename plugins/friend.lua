local W, H = gfx.width, gfx.height
local TEXT_LEFT = 108 -- Max, drawn twice his size, takes the left of the card
local TEXT_WIDTH = W - TEXT_LEFT - 8

local messages = {}
local current, frame = 1, 1
local lines, font = {}, "loud"

local function show(index)
  current = index
  -- The loud font, unless a word is too long for it: then the first smaller one that fits.
  for _, candidate in ipairs({ "loud", "medium", "small" }) do
    font = candidate
    local fits = true
    for word in messages[current]:gmatch("%S+") do
      if gfx.textWidth(word, font) > TEXT_WIDTH then fits = false end
    end
    if fits then break end
  end
  lines = gfx.wrap(messages[current], TEXT_WIDTH, font)
end

function load()
  messages = {}
  for message in config.messages:gmatch("[^|]+") do
    message = message:match("^%s*(.-)%s*$")
    if message ~= "" then messages[#messages + 1] = message end
  end
  if #messages == 0 then messages = MESSAGES end
  show(1)
end

function update()
  frame = frame % #walk + 1
end

function draw()
  gfx.rect(5, 5, W - 10, H - 10, "#0e7a00", 8)
  local image = walk[frame]
  gfx.draw(image, 4, (H - image.height * 2) // 2, 2)

  local lineHeight = gfx.textHeight(font)
  local x = TEXT_LEFT + TEXT_WIDTH // 2
  local y = (H - #lines * lineHeight) // 2
  for _, line in ipairs(lines) do
    gfx.text(x + 1, y + 1, line, "black", font, "center") -- a one pixel shadow
    gfx.text(x, y, line, "white", font, "center")
    y = y + lineHeight
  end
end

function button(name)
  if name ~= "center" then return false end
  show(current % #messages + 1)
  return true
end
